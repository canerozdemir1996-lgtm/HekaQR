import { readdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";

const root = process.cwd();
const testsRoot = path.join(root, "tests");
const output = path.join(root, "lib", "generated-test-catalog.ts");

async function walk(directory) {
  const entries = await readdir(directory, { withFileTypes: true });
  const nested = await Promise.all(entries.map((entry) => {
    const target = path.join(directory, entry.name);
    return entry.isDirectory() ? walk(target) : target.endsWith(".ts") ? [target] : [];
  }));
  return nested.flat();
}

const files = (await walk(testsRoot)).sort();
const catalog = [];

for (const absolutePath of files) {
  const source = await readFile(absolutePath, "utf8");
  const relativePath = path.relative(root, absolutePath).replaceAll("\\", "/");
  const type = relativePath.includes("/e2e/") ? "e2e" : "unit";
  const tests = [];
  const expression = /\btest\s*\(\s*(["'`])([\s\S]*?)\1\s*,/g;
  let match;
  while ((match = expression.exec(source)) !== null) {
    const name = match[2].replace(/\s+/g, " ").trim();
    if (name && !name.includes("${")) tests.push(name);
  }
  catalog.push({ file: relativePath, type, tests });
}

const generated = `// Generated by scripts/generate-test-catalog.mjs. Do not edit manually.\nexport type AdminTestCatalogEntry = {\n  file: string;\n  type: "unit" | "e2e";\n  tests: string[];\n};\n\nexport const adminTestCatalog: AdminTestCatalogEntry[] = ${JSON.stringify(catalog, null, 2)};\n`;
await writeFile(output, generated, "utf8");
console.log(`Generated ${catalog.length} files and ${catalog.reduce((sum, item) => sum + item.tests.length, 0)} tests.`);
